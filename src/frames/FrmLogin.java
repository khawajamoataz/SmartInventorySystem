    private void BtnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnLoginActionPerformed
     

if (!ValidationUtil.isEmpty(TxtUserName, TxtPassword)) {
    return;
}

String username = TxtUserName.getText().trim();
String password = TxtPassword.getText().trim();

try {
    String contents = FilesTest1.readFile("users.txt");
    String lines[] = contents.split("\n");
    boolean found = false;
    
    for(int i = 0; i < lines.length; i++){
        String row[] = lines[i].split(","); 
        String user = row[0].trim();
        String pass = row[1].trim();
        
        if(username.equals(user) && password.equals(pass)){
            found = true;
            break;
        }
    }
    
    if(found) {
        FrmDashBoard dash = new FrmDashBoard();
        dash.setVisible(true);
        this.setVisible(false);
    } else {
        JOptionPane.showMessageDialog(this, "Invalid username or password");
    }
    
} catch (Exception ex) {
    JOptionPane.showMessageDialog(this, "Error reading users.txt file!");
}



    }//GEN-LAST:event_BtnLoginActionPerformed

